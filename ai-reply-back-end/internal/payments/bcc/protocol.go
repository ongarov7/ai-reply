// FormatKZT converts tiyn to the exact request representation without floating
// point or overflow, including at math.MaxInt64. Zero is valid as a money value;
// whether an operation permits it belongs to that operation's business rules.
func FormatKZT(tiyn int64) (string, error) {
	if tiyn < 0 {
		return "", ErrInvalidAmount
	}
	return fmt.Sprintf("%d.%02d", tiyn/100, tiyn%100), nil
}

// ParseKZT accepts only the canonical representation generated by FormatKZT.
// It does not guess the units of integer, exponent or locale-formatted input.
func ParseKZT(amount string) (int64, error) {
	if len(amount) < 4 || len(amount) > 20 || amount[len(amount)-3] != '.' {
		return 0, ErrInvalidAmount
	}
	whole, fraction := amount[:len(amount)-3], amount[len(amount)-2:]
	if !digits(whole) || !digits(fraction) || len(whole) > 1 && whole[0] == '0' {
		return 0, ErrInvalidAmount
	}
	value, err := strconv.ParseInt(whole+fraction, 10, 64)
	if err != nil {
		return 0, ErrInvalidAmount
	}
	return value, nil
}

func digits(s string) bool {
	return s != "" && strings.IndexFunc(s, func(r rune) bool { return r < '0' || r > '9' }) == -1
}

func printableASCII(s string) bool {
	for _, b := range []byte(s) {
		if b < 0x20 || b > 0x7e {
			return false
		}
	}
	return true
}
