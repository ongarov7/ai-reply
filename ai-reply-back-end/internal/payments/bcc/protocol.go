// Package bcc implements the documented BCC request primitives. It does not
// implement payments.Provider, accept callbacks, send money or grant purchases.
//
// In particular, a successful TRTYPE=90 response is not proof that the original
// payment succeeded. The bank's original-operation response contract still needs
// confirmation before an application can use it to fulfil a purchase.
package bcc

import (
	"errors"
	"fmt"
	"strconv"
	"strings"
)

type Environment string

const (
	Sandbox    Environment = "sandbox"
	Production Environment = "production"

	SandboxEndpoint    = "https://test3ds.bcc.kz:5445/cgi-bin/cgi_link"
	ProductionEndpoint = "https://3dsecure.bcc.kz/webview"
	CurrencyKZT        = "398"
)

var (
	ErrInvalidConfig          = errors.New("bcc: invalid configuration")
	ErrInvalidRequest         = errors.New("bcc: invalid request")
	ErrInvalidAmount          = errors.New("bcc: invalid KZT amount")
	ErrInvalidKey             = errors.New("bcc: invalid MAC key")
	ErrUnsupportedTransaction = errors.New("bcc: unsupported transaction type")
	ErrUnsupportedResponse    = errors.New("bcc: unsupported gateway response")
	ErrOriginalStatusUnknown  = errors.New("bcc: original transaction status contract is not implemented")
	ErrQueryWindowExpired     = errors.New("bcc: the 24-hour status query window has expired")
	ErrUnavailable            = errors.New("bcc: gateway request unavailable")
	ErrResponseTooLarge       = errors.New("bcc: gateway response exceeds the size limit")
)

// Endpoint returns the exact documented endpoint; there is no default environment.
func (e Environment) Endpoint() (string, error) {
	switch e {
	case Sandbox:
		return SandboxEndpoint, nil
	case Production:
		return ProductionEndpoint, nil
	default:
		return "", ErrInvalidConfig
	}
}

// ValidateEndpoint rejects cross-environment endpoints, arbitrary hosts, altered
// ports, credentials, query strings and fragments. Custom URLs are not supported.
func ValidateEndpoint(environment Environment, endpoint string) error {
	want, err := environment.Endpoint()
	if err != nil || endpoint != want {
		return ErrInvalidConfig
	}
	return nil
}

