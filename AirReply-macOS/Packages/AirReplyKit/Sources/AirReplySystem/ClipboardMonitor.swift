import AppKit

/// Text another app put on the general pasteboard, shown in the quick bar as
/// "reply to". Only read when the user opens the panel.
public struct CopiedText: Equatable, Sendable {
    public let text: String
    public let changeCount: Int
    /// When this monitor first saw the change (macOS keeps no copy time).
    public let observedAt: Date

    public init(text: String, changeCount: Int, observedAt: Date) {
        self.text = text
        self.changeCount = changeCount
        self.observedAt = observedAt
    }
}

public enum CopiedTextResult: Equatable, Sendable {
    /// Nothing new since the last panel opening, too old, empty, or our own reply.
    case none
    case text(CopiedText)
    /// Marked by a password manager as concealed or transient: never shown.
    case concealed
    /// The user denied this app pasteboard access in System Settings.
    case denied
}

/// The pasteboard calls the monitor makes, so tests can use a fake.
@MainActor
public protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    /// Types on the pasteboard; reading them does not read contents.
    var types: [NSPasteboard.PasteboardType] { get }
    /// True when macOS will refuse programmatic reads for this app.
    var isAccessDenied: Bool { get }
    func readString() -> String?
    /// Replaces the contents with plain text and returns the new change count.
    func writeString(_ string: String) -> Int
}

/// Watches only the pasteboard change counter (a cheap integer, contents are not
/// read) so a copy can be dated; reads the text on demand.
@MainActor
public final class ClipboardMonitor {
    /// Markers that password managers and clipboard tools put on items nobody should show or keep
    /// (nspasteboard.org conventions, plus 1Password's own type).
    static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    private let pasteboard: any PasteboardAccess
    private let now: @MainActor () -> Date
    private(set) var timer: Timer?
    /// The change count when the monitor started; it and anything before are never offered. Nil while stopped.
    private var baseline: Int?
    /// The latest change count seen and when it was first seen.
    private var lastSeen: (changeCount: Int, at: Date)?
    private var ownChangeCounts: Set<Int> = []
    private var handledChangeCounts: Set<Int> = []
    /// Each read may show the macOS paste prompt, so a change is read at most once.
    private var lastRead: (changeCount: Int, text: String?)?

    public init(pasteboard: PasteboardAccess = SystemPasteboard(), now: @escaping @MainActor () -> Date = Date.init) {
        self.pasteboard = pasteboard
        self.now = now
    }

    isolated deinit {
        timer?.invalidate()
    }

    /// Starts the change-count timer (about once a second, with tolerance).
    public func start() {
        guard timer == nil else { return }
        baseline = pasteboard.changeCount
        let timer = Timer(timeInterval: 1.0, repeats: true) { [weak self] timer in
            guard let self else {
                timer.invalidate()
                return
            }
            MainActor.assumeIsolated { self.poll() }
        }
        timer.tolerance = 0.5
        // Common modes keep it ticking while a menu is open or a window is being dragged.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
        baseline = nil
        lastSeen = nil
        lastRead = nil
        ownChangeCounts = []
        handledChangeCounts = []
    }

    /// Called when the panel opens. Returns text another app copied within `maxAge`
    /// after this monitor started, until it is marked handled; never returns text this app wrote.
    public func takeFreshCopiedText(maxAge: TimeInterval) -> CopiedTextResult {
        guard let baseline else { return .none }
        let count = pasteboard.changeCount
        guard count != baseline, !ownChangeCounts.contains(count), !handledChangeCounts.contains(count) else {
            return .none
        }
        let now = self.now()
        let observedAt: Date
        if let lastSeen, lastSeen.changeCount == count {
            observedAt = lastSeen.at
        } else {
            // Copied less than a tick ago: the timer has not dated it yet.
            observe(count, at: now)
            observedAt = now
        }
        guard now.timeIntervalSince(observedAt) <= maxAge else { return .none }
        // Only metadata so far: a denied or concealed pasteboard is never read.
        if pasteboard.isAccessDenied { return .denied }
        let types = pasteboard.types
        if types.contains(where: Self.concealedTypes.contains) {
            handledChangeCounts.insert(count)
            return .concealed
        }
        // Files copied in Finder carry their names as text too; that is not a message.
        guard types.contains(.string), !types.contains(.fileURL) else { return .none }
        guard let text = readString(changeCount: count),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return .none }
        return .text(CopiedText(text: text, changeCount: count, observedAt: observedAt))
    }

    /// The user dismissed this copied text or already replied to it: do not offer it again.
    public func markHandled(_ copied: CopiedText) {
        handledChangeCounts.insert(copied.changeCount)
        if lastRead?.changeCount == copied.changeCount { lastRead = nil }
    }

    /// Puts a generated reply on the pasteboard and remembers it as our own.
    public func copy(_ text: String) {
        ownChangeCounts.insert(pasteboard.writeString(text))
        lastRead = nil
    }

    /// One timer tick: dates a new change without reading it.
    func poll() {
        let count = pasteboard.changeCount
        if count != lastSeen?.changeCount { observe(count, at: now()) }
    }

    private func observe(_ count: Int, at date: Date) {
        lastSeen = (count, date)
        // Only the current change count can match again; drop marks and text for the others.
        ownChangeCounts = ownChangeCounts.filter { $0 == count }
        handledChangeCounts = handledChangeCounts.filter { $0 == count }
        if lastRead?.changeCount != count { lastRead = nil }
    }

    private func readString(changeCount count: Int) -> String? {
        if let lastRead, lastRead.changeCount == count { return lastRead.text }
        let text = pasteboard.readString()
        // Replaced while we were reading (perhaps by a password manager): show nothing.
        guard pasteboard.changeCount == count else { return nil }
        lastRead = (count, text)
        return text
    }
}

/// `NSPasteboard.general` behind `PasteboardAccess`.
@MainActor
public final class SystemPasteboard: PasteboardAccess {
    public init() {}

    public var changeCount: Int { NSPasteboard.general.changeCount }
    public var types: [NSPasteboard.PasteboardType] { NSPasteboard.general.types ?? [] }

    public var isAccessDenied: Bool {
        // The per-app pasteboard privacy setting exists from macOS 15.4.
        if #available(macOS 15.4, *) {
            return NSPasteboard.general.accessBehavior == .alwaysDeny
        }
        return false
    }

    public func readString() -> String? {
        NSPasteboard.general.string(forType: .string)
    }

    public func writeString(_ string: String) -> Int {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(string, forType: .string)
        return pasteboard.changeCount
    }
}
