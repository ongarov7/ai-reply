package kz.yerek.aireply.keyboard.emoji

import android.content.res.AssetManager
import android.graphics.Paint
import java.io.InputStream
import java.util.concurrent.ConcurrentHashMap

/**
 * The categories of the shared catalog, in its order (the Unicode CLDR one).
 * [id] is the `@<id>` line that starts each one in the file.
 */
enum class EmojiCategory(val id: String) {
    SMILEYS_EMOTION("smileys_emotion"),
    PEOPLE_BODY("people_body"),
    ANIMALS_NATURE("animals_nature"),
    FOOD_DRINK("food_drink"),
    TRAVEL_PLACES("travel_places"),
    ACTIVITIES("activities"),
    OBJECTS("objects"),
    SYMBOLS("symbols"),
    FLAGS("flags");

    companion object {
        fun fromId(id: String): EmojiCategory? = entries.firstOrNull { it.id == id }
    }
}

/** One emoji of the catalog and the Emoji version that brought it ("15.1"). */
data class EmojiEntry(val emoji: String, val version: String)

/** One category's emoji, in catalog order. */
data class EmojiGroup(val category: EmojiCategory, val entries: List<EmojiEntry>)

/**
 * The emoji the keyboard offers: the catalog both keyboards share
 * (`assets/emoji/emoji-catalog.txt`, generated by `tools/emoji`), less what
 * this phone's font cannot draw ([filtered]).
 *
 * Эмодзи каталогы: iOS-пен ортақ тізім, телефон сала алмайтындары алынып тасталады.
 */
class EmojiCatalog(val groups: List<EmojiGroup>) {

    val size: Int get() = groups.sumOf { it.entries.size }

    /** Every emoji, for checking a stored recent against what is offered. */
    val all: Set<String> by lazy { groups.flatMapTo(HashSet()) { group -> group.entries.map { it.emoji } } }

    /** Only the emoji [support] can draw; a category left empty is dropped. */
    fun filtered(support: EmojiSupport): EmojiCatalog = EmojiCatalog(
        groups.mapNotNull { group ->
            group.entries.filter { support.isSupported(it.emoji) }
                .takeIf { it.isNotEmpty() }
                ?.let { EmojiGroup(group.category, it) }
        }
    )

    companion object {
        val EMPTY = EmojiCatalog(emptyList())
    }
}

/**
 * Reads the catalog's text format:
 *
 *     @smileys_emotion
 *     😀<TAB>1.0
 *
 * A line starting with `@` starts a category; every other line is an emoji,
 * a tab and its Emoji version. Pure, so the shipped file is checked on the JVM.
 * Tolerant the way a reader of a shared file should be: blank lines, a
 * Windows line end, a category this build does not know (its emoji are
 * skipped), a line before any category and a repeated emoji are all ignored
 * rather than failing the whole page.
 */
object EmojiCatalogParser {

    fun parse(text: String): EmojiCatalog {
        val groups = LinkedHashMap<EmojiCategory, MutableList<EmojiEntry>>()
        val seen = HashSet<String>()
        var current: MutableList<EmojiEntry>? = null
        text.lineSequence().forEach { raw ->
            val line = raw.trimEnd('\r')
            when {
                line.isBlank() -> Unit
                line.startsWith("@") -> {
                    val category = EmojiCategory.fromId(line.substring(1).trim())
                    current = category?.let { groups.getOrPut(it) { mutableListOf() } }
                }
                else -> {
                    val tab = line.indexOf('\t')
                    val emoji = (if (tab >= 0) line.substring(0, tab) else line).trim()
                    val version = if (tab >= 0) line.substring(tab + 1).trim() else ""
                    if (emoji.isNotEmpty() && seen.add(emoji)) current?.add(EmojiEntry(emoji, version))
                }
            }
        }
        return EmojiCatalog(
            EmojiCategory.entries.mapNotNull { category ->
                groups[category]?.takeIf { it.isNotEmpty() }?.let { EmojiGroup(category, it) }
            }
        )
    }
}

/** Whether this phone draws an emoji as one picture. */
fun interface EmojiSupport {
    fun isSupported(emoji: String): Boolean
}

/**
 * The system font's answer: `Paint.hasGlyph` is true for a sequence only when
 * the font has ONE glyph for it - so a flag or a family the font does not
 * know is left out instead of showing as two letters or three faces. Answers
 * are kept, as the font does not change while the keyboard runs.
 */
class PaintEmojiSupport(private val paint: Paint = Paint()) : EmojiSupport {

    private val answers = ConcurrentHashMap<String, Boolean>()

    override fun isSupported(emoji: String): Boolean =
        answers.getOrPut(emoji) { synchronized(paint) { runCatching { paint.hasGlyph(emoji) }.getOrDefault(false) } }
}

/** The catalog file, from the APK or (in tests) from the source tree. */
fun interface EmojiSource {
    fun open(): InputStream
}

class AssetEmojiSource(private val assets: AssetManager) : EmojiSource {
    override fun open(): InputStream = assets.open(PATH, AssetManager.ACCESS_STREAMING)

    companion object {
        const val PATH = "emoji/emoji-catalog.txt"
    }
}

/**
 * The catalog this phone shows, read and filtered once per process - the
 * file is about 30 KB and the font checks take a moment on an old phone, so
 * neither happens twice, and never on the main thread.
 */
object EmojiCatalogCache {

    @Volatile
    private var loaded: EmojiCatalog? = null

    /** Blocking: call it off the main thread. */
    fun load(source: EmojiSource, support: EmojiSupport): EmojiCatalog {
        loaded?.let { return it }
        synchronized(this) {
            loaded?.let { return it }
            val parsed = runCatching {
                source.open().bufferedReader(Charsets.UTF_8).use { EmojiCatalogParser.parse(it.readText()) }
            }.getOrDefault(EmojiCatalog.EMPTY)
            // A read that failed is not remembered: the next show tries again.
            return parsed.filtered(support).also { if (it.size > 0) loaded = it }
        }
    }
}
